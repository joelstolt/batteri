export const publicProducts = products.filter((p) => !p.hidden)

// ─── Helpers ───

export function getProductsByCategory(slug) {
  return publicProducts.filter((p) => p.category === slug)
}

export function getProductBySlug(slug) {
  return products.find((p) => p.slug === slug) || null
}

export function getProductImage(product) {
  return product.images?.[0] || "/produkter/placeholder.jpg"
}

export function getProductBrand(product) {
  return product?.specs?.["Varumärke"] || "Batteriproffs"
}

export function getProductChemistry(product) {
  const t = product?.specs?.["Typ"] || ""
  if (/gel/i.test(t)) return "Gelbatteri"
  if (/dry ?cell|agm|vrla/i.test(t)) return "AGM / Dry Cell"
  if (/öppet|ventilerat|blybatteri/i.test(t)) return "Öppet blybatteri"
  return "Blybatteri"
}
